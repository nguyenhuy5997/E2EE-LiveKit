"""Make LiveKit access tokens for the EVT2 test app (standard library only).

The API key and secret are read from the environment, never from the command line or the repo:

    set LIVEKIT_API_KEY=APIxxxxxxxx
    set LIVEKIT_API_SECRET=xxxxxxxxxxxxxxxx
    py -3 tools/make_token.py --room evt2-test phone1 phone2

Each identity gets one token (valid --hours, default 24) that may join, publish, subscribe, send data and set its
own attributes in --room.
Paste the token into the app's "URL & Token" tab together with the project URL (wss://<project>.livekit.cloud).

--write-app also writes the tokens and LIVEKIT_URL into the app (Evt2Tokens.kt), so the start screen only asks which
phone this is ("Máy 1", "Máy 2", ...). Rebuild the app afterwards; rerun it when the tokens expire or the API key
changes:

    set LIVEKIT_URL=wss://<project>.livekit.cloud
    py -3 tools/make_token.py --room evt2-test --hours 8760 --write-app phone1 phone2 phone3 phone4
"""
import argparse
import base64
import hashlib
import hmac
import json
import os
import sys
import time
from datetime import datetime, timezone

APP_TOKENS_KT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "sample-app-common", "src", "main",
                             "java", "io", "livekit", "android", "sample", "Evt2Tokens.kt")


def b64url(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode("ascii")


def make_token(api_key: str, api_secret: str, identity: str, room: str, ttl_s: int) -> str:
    now = int(time.time())
    header = {"alg": "HS256", "typ": "JWT"}
    claims = {
        "iss": api_key,
        "sub": identity,
        "name": identity,
        "nbf": now - 10,
        "exp": now + ttl_s,
        "video": {
            "room": room,
            "roomJoin": True,
            "canPublish": True,
            "canSubscribe": True,
            "canPublishData": True,
            # the app publishes its E2EE mode as a participant attribute (mode mismatch warning)
            "canUpdateOwnMetadata": True,
        },
    }
    signing_input = (b64url(json.dumps(header, separators=(",", ":")).encode())
                     + "." + b64url(json.dumps(claims, separators=(",", ":")).encode()))
    sig = hmac.new(api_secret.encode(), signing_input.encode("ascii"), hashlib.sha256).digest()
    return signing_input + "." + b64url(sig)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("identities", nargs="+", help="participant identities, one token each")
    ap.add_argument("--room", default="evt2-test")
    ap.add_argument("--hours", type=float, default=24.0)
    ap.add_argument("--write-app", action="store_true", help="also write the tokens + LIVEKIT_URL into Evt2Tokens.kt")
    args = ap.parse_args()

    api_key = os.environ.get("LIVEKIT_API_KEY")
    api_secret = os.environ.get("LIVEKIT_API_SECRET")
    if not api_key or not api_secret:
        print("Set LIVEKIT_API_KEY and LIVEKIT_API_SECRET first.", file=sys.stderr)
        return 1

    ttl_s = int(args.hours * 3600)
    tokens = [(identity, make_token(api_key, api_secret, identity, args.room, ttl_s)) for identity in args.identities]
    for identity, token in tokens:
        print(f"{identity}: {token}")

    if args.write_app:
        url = os.environ.get("LIVEKIT_URL")
        if not url:
            print("Set LIVEKIT_URL (wss://<project>.livekit.cloud) for --write-app.", file=sys.stderr)
            return 1
        expires = datetime.fromtimestamp(time.time() + ttl_s, timezone.utc).strftime("%Y-%m-%d")
        write_app_tokens(url, args.room, expires, tokens)
        print(f"wrote {os.path.normpath(APP_TOKENS_KT)} ({len(tokens)} tokens, valid until {expires} UTC)")
    return 0


def write_app_tokens(url, room, expires, tokens):
    entries = "\n".join(f'        "{identity}" to "{token}",' for identity, token in tokens)
    with open(APP_TOKENS_KT, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"""package io.livekit.android.sample

/**
 * EVT2: LiveKit server URL and one access token per phone, built into the app so nobody has to type them.
 * Generated by tools/make_token.py --write-app (room "{room}", valid until {expires} UTC); do not edit by hand.
 * Each phone picks a different entry ("Máy 1", "Máy 2", ...): LiveKit allows one connection per identity.
 */
object Evt2Tokens {{
    const val URL = "{url}"
    const val ROOM = "{room}"
    const val EXPIRES = "{expires}"

    /** identity to token, in the order shown on the start screen. */
    val TOKENS: List<Pair<String, String>> = listOf(
{entries}
    )
}}
""")


if __name__ == "__main__":
    sys.exit(main())
